def parse_outline_fields(outline: str) -> dict[str, str]:
    """Parse the eight supported outline fields from inline or block values."""

    # Models occasionally prepend a short meta sentence and glue the first required
    # field to it on the same line. The first supported field is an unambiguous
    # contract boundary, so drop any model preamble before it deterministically.
    first_field = REQUIRED_OUTLINE_FIELDS[0]
    for marker in (f"{first_field}：", f"{first_field}:"):
        position = outline.find(marker)
        if position > 0:
            outline = outline[position:]
            break

    values: dict[str, str] = {}
    current_label: str | None = None
    current_lines: list[str] = []

    def flush() -> None:
        if current_label is None:
            return
        value = "\n".join(current_lines).strip()
        if value:
            values[current_label] = value

    field_labels = "|".join(re.escape(field) for field in REQUIRED_OUTLINE_FIELDS)
    field_pattern = re.compile(
        rf"^\s*(?:[-*]\s*)?({field_labels})\s*[：:](.*)$"
    )
    for raw_line in outline.splitlines():
        stripped = raw_line.strip()
        if re.match(r"^#{1,6}(?:\s|$)", stripped):
            flush()
            current_label = None
            current_lines = []
            continue
        match = field_pattern.match(raw_line)
        if match:
            flush()
            current_label = match.group(1)
            inline_value = match.group(2).strip()
            current_lines = [inline_value] if inline_value else []
            continue
        if current_label is not None and stripped:
            current_lines.append(stripped)
    flush()
    return values


def validate_current_outline(outline: str) -> None:
    values = parse_outline_fields(outline)
    missing = [field for field in REQUIRED_OUTLINE_FIELDS if not values.get(field)]
    if missing:
        raise HardGateError(missing)


def _display_value(value: Any) -> str:
    if value is None:
        return "（未填写）"
    if isinstance(value, (list, tuple)):
        return "；".join(_display_value(item) for item in value)
    if isinstance(value, Mapping):
        return "；".join(f"{key}：{_display_value(item)}" for key, item in value.items())
    return str(value).strip() or "（未填写）"


def format_references(references: Iterable[Mapping[str, Any]]) -> str:
    lines: list[str] = []
    fields = (
        "program_id",
        "story_phase",
        "input_state",
        "central_pressure",
        "reusable_program",
        "applicable_conditions",
        "failure_modes",
        "anti_repetition_notes",
        "output_state",
    )
    for index, reference in enumerate(references, start=1):
        lines.append(f"Reference Program {index}")
        for field in fields:
            lines.append(f"{field}: {_display_value(reference.get(field))}")
        lines.append("")
    return "\n".join(lines).strip() or "（本次未选择 Reference Program）"


def _input_block(title: str, value: str) -> str:
    return f"## {title}\n\n{value.strip() or '（未填写）'}"


def _extract_markdown_block(content: str, heading: str) -> str:
    lines = content.splitlines()
    for index, line in enumerate(lines):
        if line.strip() != heading:
            continue
        collected: list[str] = []
        for next_line in lines[index + 1:]:
            stripped = next_line.strip()
            if stripped.startswith("# ") or (heading.startswith("## ") and stripped.startswith("## ")):
                break
            collected.append(next_line)
        return "\n".join(collected).strip()
    return ""


